import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources=['core','scene','events','game','loot','save','equipment','camp','music','identity','action-dock','bosses','expedition','chronicle','expedition-save','places','npc-world','npc-events','npc-save','looks-expanded','pets','pet-ui','release','ui'];
const bundle='/* Generated by scripts/build.mjs. Edit the source modules, not this file. */\n'+sources.map(name=>`\n/* === ${name}.js === */\n${fs.readFileSync(path.join(root,'js',name+'.js'),'utf8')}\n;`).join('\n');
const css=fs.readFileSync(path.join(root,'css/game.css'),'utf8');
const version=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8')).version;
const revision=createHash('sha256').update(bundle).update(css).update(version).update(fs.readFileSync(path.join(root,'assets/heroes-expansion.png'))).digest('hex').slice(0,12);
const metadata={version,revision};
fs.writeFileSync(path.join(root,'version.json'),JSON.stringify(metadata,null,2)+'\n');
fs.writeFileSync(path.join(root,'js/game.bundle.js'),'const APP_RELEASE=Object.freeze('+JSON.stringify(metadata)+');\n'+bundle);
let html=fs.readFileSync(path.join(root,'index.html'),'utf8');
html=html.replace(/<script defer src="js\/[^\"]+"><\/script>\s*/g,'');
html=html.replace('</head>',`<script defer src="js/game.bundle.js?v=${revision}"></script>\n</head>`);
html=html.replace(/css\/game.css\?v=[^\"]+/g,`css/game.css?v=${revision}`);
fs.writeFileSync(path.join(root,'index.html'),html);
console.log(`Built ${sources.length} modules, ${Buffer.byteLength(bundle)} bytes; revision ${revision}`);
